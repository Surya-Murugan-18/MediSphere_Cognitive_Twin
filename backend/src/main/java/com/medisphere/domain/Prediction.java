package com.medisphere.domain;

import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;
import org.springframework.data.annotation.CreatedDate;
import org.springframework.data.annotation.Id;
import org.springframework.data.mongodb.core.index.CompoundIndex;
import org.springframework.data.mongodb.core.index.CompoundIndexes;
import org.springframework.data.mongodb.core.index.TextIndexed;
import org.springframework.data.mongodb.core.mapping.Document;

import java.time.Instant;
import java.util.List;

/**
 * AI Risk Prediction document — one per model run per patient.
 * Collection: predictions
 *
 * SHAP factors and clinical evidence are embedded in the document,
 * not stored in separate collections. This allows a single read to
 * retrieve the full explanation.
 *
 * Per design.md §4.7
 */
@Document(collection = "predictions")
@CompoundIndexes({
    @CompoundIndex(name = "patient_model_date_idx",
                   def  = "{'patientId':1,'model':1,'createdAt':-1}"),
    @CompoundIndex(name = "patient_category_idx",
                   def  = "{'patientId':1,'category':1}")
})
@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class Prediction {

    /** Format: PR-xxxx (generated by PredictionService) */
    @Id
    private String id;

    /** References patients._id */
    private String patientId;

    /** Model name e.g. "CVD-Risk-v3.2", "DM-Complication-v2.4", "Readmit-30d-v1.8" */
    @TextIndexed
    private String model;

    /** Human-readable label e.g. "10-Year Cardiovascular Risk" */
    @TextIndexed
    private String label;

    /** Risk percentage 0.0–100.0 */
    private double value;

    /** High | Medium | Low */
    private String category;

    /** Federated learning round that produced this model version */
    @Builder.Default
    private int federatedRound = 47;

    /** Model confidence score 0–100 */
    private int confidence;

    /** Calibration status: Calibrated | Recalibration Due */
    @Builder.Default
    private String calibration = "Calibrated";

    /** Embedded SHAP feature contributions */
    private List<ShapFactor> shapFactors;

    /** Embedded clinical evidence citations */
    private List<ClinicalEvidence> clinicalEvidence;

    @CreatedDate
    private Instant createdAt;

    // ── Embedded types ─────────────────────────────────────────────────────

    /**
     * One SHAP feature contribution entry.
     * contribution > 0 → increases risk; contribution < 0 → decreases risk.
     */
    @Data
    @Builder
    @NoArgsConstructor
    @AllArgsConstructor
    public static class ShapFactor {
        /** Feature name e.g. "HbA1c" */
        private String feature;

        /** Contribution value (positive or negative percentage points) */
        private double contribution;

        /** Display value of the feature e.g. "8.2%" */
        private String value;

        /** "increases" or "decreases" */
        private String direction;
    }

    /**
     * One clinical evidence citation supporting the prediction.
     */
    @Data
    @Builder
    @NoArgsConstructor
    @AllArgsConstructor
    public static class ClinicalEvidence {
        private String guideline;
        private String detail;
    }
}
